create extension if not exists pgcrypto;
create schema if not exists private;

create type public.app_role as enum (
  'project_coordinator', 'it_director', 'project_analyst', 'keyuser',
  'requester', 'area_manager', 'viewer'
);
create type public.project_health as enum ('on_track', 'attention', 'late');
create type public.project_item_kind as enum ('milestone', 'task', 'subtask');
create type public.time_entry_status as enum ('running', 'paused', 'closed');
create type public.approval_decision as enum ('pending', 'approved', 'rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  legacy_id text unique,
  email text not null unique,
  display_name text not null,
  role public.app_role not null default 'keyuser',
  active boolean not null default true,
  must_change_password boolean not null default false,
  invited_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_seen_at timestamptz
);

create table public.project_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  sequence integer not null default 0,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.projects (
  id bigint generated by default as identity primary key,
  source text not null default 'platform',
  external_id text,
  code text,
  name text not null,
  project_type_id bigint references public.project_types(id) on delete set null,
  area text,
  manager_name text,
  manager_user_id uuid references public.profiles(id) on delete set null,
  status text not null default 'planning',
  health public.project_health not null default 'on_track',
  progress integer not null default 0 check (progress between 0 and 100),
  planned_start date,
  planned_end date,
  actual_start date,
  actual_end date,
  planned_hours numeric(12,2) not null default 0,
  planned_cost numeric(14,2) not null default 0,
  actual_cost numeric(14,2) not null default 0,
  project_prioritized boolean not null default false,
  prioritization_date date,
  approving_director text,
  raw_json jsonb,
  synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source, external_id),
  check (not project_prioritized or (prioritization_date is not null and approving_director is not null))
);

create index projects_status_idx on public.projects(status, health);
create index projects_area_idx on public.projects(area);

create table public.project_phases (
  id bigint generated by default as identity primary key,
  project_ref text not null,
  project_name text not null,
  name text not null,
  description text,
  sequence integer not null default 0,
  active boolean not null default true,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (project_ref, name)
);

create index project_phases_project_sequence_idx on public.project_phases(project_ref, sequence);

create table public.sprints (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  phase_id bigint references public.project_phases(id) on delete set null,
  name text not null,
  objective text,
  status text not null default 'planned',
  start_date date,
  end_date date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index sprints_project_idx on public.sprints(project_id);

create table public.project_items (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  sprint_id bigint references public.sprints(id) on delete set null,
  phase_id bigint references public.project_phases(id) on delete set null,
  parent_id bigint references public.project_items(id) on delete cascade,
  source text not null default 'platform',
  external_id text,
  kind public.project_item_kind not null,
  name text not null,
  group_name text,
  status text not null default 'planned',
  health public.project_health not null default 'on_track',
  assigned_user_id uuid references public.profiles(id) on delete set null,
  assigned_name text,
  planned_start date,
  planned_end date,
  actual_start date,
  actual_end date,
  planned_hours numeric(12,2) not null default 0,
  raw_json jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (source, external_id)
);

create index items_project_kind_idx on public.project_items(project_id, kind);
create index items_assignee_idx on public.project_items(assigned_user_id);
create index items_parent_idx on public.project_items(parent_id);

create table public.project_members (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  allocation_percent integer not null default 0 check (allocation_percent between 0 and 100),
  role_name text,
  created_at timestamptz not null default now(),
  unique (project_id, user_id)
);

create table public.time_entries (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  item_id bigint not null references public.project_items(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete restrict,
  activity text,
  status public.time_entry_status not null default 'running',
  started_at timestamptz not null,
  ended_at timestamptz,
  paused_seconds integer not null default 0 check (paused_seconds >= 0),
  total_minutes integer check (total_minutes >= 0),
  source text not null default 'timer',
  created_at timestamptz not null default now()
);

create index time_entries_user_status_idx on public.time_entries(user_id, status);
create index time_entries_project_idx on public.time_entries(project_id);
create unique index one_running_entry_per_user_idx on public.time_entries(user_id)
  where status = 'running';

