create or replace function private.current_role()
returns public.app_role
language sql
stable
security definer
set search_path = ''
as $$
  select role from public.profiles where id = auth.uid() and active = true
$$;

create or replace function private.can_manage_projects()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_role() in ('project_coordinator', 'it_director', 'project_analyst'), false)
$$;

create or replace function private.can_manage_users()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(private.current_role() in ('project_coordinator', 'it_director'), false)
$$;

grant usage on schema private to authenticated;
grant execute on function private.current_role() to authenticated;
grant execute on function private.can_manage_projects() to authenticated;
grant execute on function private.can_manage_users() to authenticated;

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, display_name, role, must_change_password)
  values (
    new.id,
    lower(new.email),
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), split_part(new.email, '@', 1)),
    case
      when new.raw_app_meta_data ->> 'role' in (
        'project_coordinator', 'it_director', 'project_analyst', 'keyuser',
        'requester', 'area_manager', 'viewer'
      ) then (new.raw_app_meta_data ->> 'role')::public.app_role
      else 'keyuser'::public.app_role
    end,
    coalesce((new.raw_user_meta_data ->> 'must_change_password')::boolean, false)
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

